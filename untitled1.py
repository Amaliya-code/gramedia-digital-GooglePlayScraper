def cobit_domain(text):

    text = str(text).lower()

    if any(k in text for k in ['premium','langganan','informasi']):
        return 'EDM05'

    elif any(k in text for k in ['fitur','pengembangan','menu']):
        return 'APO05'

    elif any(k in text for k in ['error','crash','loading','lemot']):
        return 'BAI04'

    elif any(k in text for k in ['customer service','cs','live chat']):
        return 'DSS01'

    else:
        return 'MEA01'

df['Domain_COBIT'] = df['Review'].apply(cobit_domain)

print(df[['Review','Domain_COBIT']].head())

domain_count = df['Domain_COBIT'].value_counts()

print(domain_count)