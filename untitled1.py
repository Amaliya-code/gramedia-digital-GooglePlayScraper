from google_play_scraper import reviews
import pandas as pd

result, continuation_token = reviews(
    'com.appsfoundry.scoop',  # Gramedia Digital
    lang='id',
    country='id',
    count=500
)

print("Jumlah Review:", len(result))

for r in result[:5]:
    print(r['score'])
    print(r['content'])
    print("------------------")

data = []

for r in result:
    data.append({
        'Tanggal': r['at'],
        'Rating': r['score'],
        'Review': r['content']
    })

df = pd.DataFrame(data)

print(df.head())

df.to_excel("Review_Gramedia_Digital.xlsx", index=False)

print("Data berhasil disimpan")

def sentiment(rating):
    if rating >= 4:
        return "Positif"
    elif rating == 3:
        return "Netral"
    else:
        return "Negatif"

df["Sentimen"] = df["Rating"].apply(sentiment)

print(df["Sentimen"].value_counts())

keyword_cs = [
    "customer service",
    "cs",
    "live chat",
    "admin",
    "respon",
    "balasan"
]

cs_review = df[
    df['Review'].str.contains(
        '|'.join(keyword_cs),
        case=False,
        na=False
    )
]

print(cs_review[['Rating','Review']])

